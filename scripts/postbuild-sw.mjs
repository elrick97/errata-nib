// Runs after `vite build`. Generates dist/sw.js (offline precache service worker) and dist/.nojekyll.
// Usage: node scripts/postbuild-sw.mjs
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const SW_NAME = 'sw.js';
const CACHE_PREFIX = 'errata-nib-';

if (!existsSync(join(DIST, 'index.html'))) {
  console.error('postbuild-sw: dist/index.html not found. Run `vite build` first.');
  process.exit(1);
}

// .nojekyll stops GitHub Pages from running Jekyll (which would hide _-prefixed assets).
writeFileSync(join(DIST, '.nojekyll'), '');

function listFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full));
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

const toRel = (abs) => relative(DIST, abs).split(sep).join('/');

const allFiles = listFiles(DIST)
  .map((abs) => ({ abs, rel: toRel(abs) }))
  .filter((f) => f.rel !== SW_NAME)
  .sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));

// Version = first 10 hex chars of sha256 over every file's path and contents (sw.js excluded).
const hash = createHash('sha256');
for (const f of allFiles) {
  hash.update(f.rel);
  hash.update('\0');
  hash.update(readFileSync(f.abs));
  hash.update('\0');
}
const VERSION = hash.digest('hex').slice(0, 10);
const CACHE = CACHE_PREFIX + VERSION;

// Precache: everything in dist except sw.js and dotfiles (e.g. .nojekyll).
const precacheFiles = allFiles.filter((f) => !f.rel.split('/').some((seg) => seg.startsWith('.')));
const PRECACHE = ['./', ...precacheFiles.map((f) => './' + encodeURI(f.rel))];
let totalBytes = 0;
for (const f of precacheFiles) totalBytes += statSync(f.abs).size;

const sw = `/* ERRATA service worker. Generated by scripts/postbuild-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(VERSION)};
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE = ${JSON.stringify(CACHE)};
const INDEX = './index.html';
const PRECACHE = ${JSON.stringify(PRECACHE, null, 2)};

// Responses are stored under plain URL keys (no query string). Matching ignores Vary, because
// crossorigin script/style requests carry an Origin header and Vary: Origin would otherwise miss.
const MATCH_OPTS = { ignoreSearch: true, ignoreVary: true };
function plainKey(u) {
  const k = new URL(u, self.location.href);
  k.search = '';
  k.hash = '';
  return k.href;
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) =>
        Promise.all(
          PRECACHE.map((u) =>
            fetch(new Request(u, { cache: 'reload' })).then((res) => {
              if (!res.ok) throw new Error('precache failed: ' + u + ' ' + res.status);
              return cache.put(plainKey(u), res);
            })
          )
        )
      )
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE)
            .map((k) => caches.delete(k))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(handle(req));
});

async function handle(req) {
  const cache = await caches.open(CACHE);
  if (req.mode === 'navigate') {
    const shell = await cache.match(plainKey(INDEX), MATCH_OPTS);
    if (shell) return shell;
    const root = await cache.match(plainKey('./'), MATCH_OPTS);
    if (root) return root;
    return fetch(req);
  }
  // Keys are the request URL minus query/hash, which equals the precache key for the same path.
  const hit = await cache.match(plainKey(req.url), MATCH_OPTS);
  if (hit) return hit;
  const res = await fetch(req);
  if (res && res.ok && res.type === 'basic') {
    cache.put(plainKey(req.url), res.clone()).catch(() => {});
  }
  return res;
}

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});
`;

writeFileSync(join(DIST, SW_NAME), sw);

console.log(`postbuild-sw: version ${VERSION}`);
console.log(`postbuild-sw: precached ${PRECACHE.length} entries, ${totalBytes} bytes`);
